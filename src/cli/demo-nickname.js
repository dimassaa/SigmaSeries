// Ник демо-аккаунта (F-01-12, S-84).
//
// Ник склеивается из роли и случайного суффикса, а не вводится человеком,
// поэтому правило регистрации к нему само не применяется. Дефис, а не пробел:
// ник обязан проходить `NICK_ALLOWED`, иначе маршрут `/u/{nick}` отвергает его
// до поиска и публичный профиль демо-персоны открывается 404 (№255).
//
// Проверка внутри функции — не украшение: демо-аккаунт должен быть обычным
// аккаунтом, а не исключением из правил. Если шаблон ника однажды сломают,
// генератор остановится на создании, а не выпустит аккаунт, который нельзя
// открыть.

import { NICK_ALLOWED, NICK_MAX, NICK_SEPARATOR } from '../services/auth/validate.js';

/**
 * Ник демо-аккаунта: роль плюс случайный суффикс.
 *
 * @param {string} base роль на русском: «зритель», «администратор»
 * @param {string} suffix случайный суффикс из строчных букв и цифр
 * @returns {string}
 * @throws {Error} если ник не проходит правило регистрации
 */
export function demoNickname(base, suffix) {
  const nick = `${base}-${suffix}`;
  if (nick.length > NICK_MAX || !NICK_ALLOWED.test(nick) || NICK_SEPARATOR.test(nick)) {
    throw new Error(`ник демо-аккаунта не проходит правило регистрации: ${nick}`);
  }
  return nick;
}

//   R-SEC-03, R-SEC-05

// Единицы измерения — миллисекунды, и это не украшение: ниже почти все
// значения умножаются на эти константы и уходят в express-session (maxAge),
// в окна счётчиков и в сравнения времени. Константы в секунтах выглядели бы
// безобидно и молча занижали бы каждую длительность в тысячу раз.

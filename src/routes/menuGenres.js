// Пункты меню жанров для списковых страниц (UI-03, F-02-04).
//
// Один помощник на пять маршрутов вместо пяти одинаковых мест — по тому же
// основанию, что и правая панель (panel.js): меню должно вести себя одинаково
// на главной, в каталоге, в жанре, в подборке и в поиске, а разъезжаться
// оно может, только если его собирают в пяти местах.
//
// Меню не падает вместе со страницей: сломанный источник даёт пустой список,
// и оболочка отдаёт в шапке простую ссылку на каталог (F-00-01 §5) вместо
// слоя, который никто не просил чинить.

/**
 * Пункты меню жанров или пустой список.
 *
 * @param {any} genres источник данных меню; `null` — данные не подведены
 * @param {string} locale
 * @returns {Promise<any[]>}
 */
export async function menuGenres(genres, locale) {
  if (!genres) return [];
  try {
    return await genres.menu(locale);
  } catch {
    return [];
  }
}

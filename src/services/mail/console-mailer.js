// Почтовый шлюз: пока это вывод в консоль.
//
// Полноценный шлюз — отдельная часть F-01-12: режимы smtp и devbox,
// страница S-84 для админа, привязка письма к браузеру в демо-режиме
// (H-51). Здесь этого нет и здесь не нужно.
//
// Шлюз отвечает только за доставку одного готового письма: тема, тело и
// адрес приходят из очереди. Текст письма живёт в `i18n/mails.js`, потому
// что письмо может ждать в очереди, и собирать его здесь означало бы, что
// отправляется не тот текст, который написан.

/**
 * Письмо, напечатанное в консоль.
 *
 * Печатается целиком: обрезанная ссылка бесполезна и выглядит как ошибка, а
 * без ссылки нечего подтверждать (F-01-12 §18 — демо-режим без интернета).
 *
 * @param {{to:string, subject:string, body:string, kind:string}} job
 */
export function consoleMailer(out = process.stdout) {
  return {
    async send(job) {
      out.write([
        '',
        `┌─ письмо: ${job.subject}`,
        `│  кому:   ${job.to}`,
        `│  вид:    ${job.kind}`,
        `│`,
        ...job.body.split('\n').map((line) => `│  ${line}`),
        '└─ почтовый шлюз F-01-12 не написан, письмо напечатано здесь',
        '',
      ].join('\n'));
    },
  };
}
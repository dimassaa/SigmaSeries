// Почтовый шлюз: пока это вывод в консоль.
//
// Полноценный шлюз — отдельная фича F-01-12: два режима (smtp и devbox),
// очередь с повторами 1, 2, 4, 8, 16 минут, страница S-84 для админа и
// привязка письма к браузеру в демо-режиме (H-51). Здесь этого нет и
// здесь не нужно.
//
// Что есть: маршруты не знают, как уходит письмо, и просят отправить его
// у интерфейса. Пока интерфейс один — консоль, ссылка подтверждения
// печатается при старте сервера и человек может подтвердить адрес без
// почтовой программы. Без этого регистрация проходит только наполовину:
// аккаунт создан, подтвердить его нечем.
//
// Таблицы e_mail в базе нет намеренно. Сущность E-Mail есть в
// DOMAIN-MODEL, а её хранилище появится вместе с F-01-12, когда будет
// чем описать очередь и статусы письма.

/**
 * Письмо, напечатанное в консоль.
 *
 * Ссылка печатается целиком: иначе подтвердить адрес без почты нечем, а
 * обрезанная ссылка бесполезна и выглядит как ошибка.
 *
 * @param {{to:string, token:string, locale?:string}} message
 * @param {string} baseUrl адрес приложения, чтобы ссылка была рабочей
 */
export function consoleMailer(baseUrl = 'http://127.0.0.1:3000') {
  const out = process.stdout;

  return {
    /** Подтверждение адреса. */
    verificationEmail({ to, token, locale = 'ru' }) {
      const url = `${baseUrl}/${locale}/verify?token=${encodeURIComponent(token)}`;
      out.write([
        '',
        '┌─ письмо: подтверждение адреса',
        `│  кому:   ${to}`,
        `│  тема:   ${locale === 'ru' ? 'Подтвердите email' : 'Confirm your email'}`,
        `│  ссылка: ${url}`,
        '└─ почтовый шлюз F-01-12 не написан, письмо напечатано здесь',
        '',
      ].join('\n'));
    },

    /** Адрес уже занят: письмо другое, страница та же (R-SEC-06). */
    takenEmailNotice({ to }) {
      out.write([
        '',
        '┌─ письмо: адрес уже занят',
        `│  кому:   ${to}`,
        '│  действие: предложено восстановить пароль',
        '└─ страница регистрации ответила так же, как и для свободного адреса',
        '',
      ].join('\n'));
    },
  };
}

// Лимит частоты поиска (`search.rate_limit`, R-SEC-31).
//
// Ключа в документации до 15.10 не было — класс «поиск» был единственным без
// предела. Число подтвердил автор: 30 запросов в минуту с одного адреса.
//
// Счётчик живёт в памяти процесса, как и лимиты входа: он защищает от забытой
// страницы и случайного перебора, а не от распределённой атаки — для второй
// нужен общий счётчик, и это отдельное решение. Счёт по процессам при
// нескольких workers следовало бы делать в базе, но при штатном запуске
// процесс один (ADR-004), и лимит в 30 запросов на процесс достаточно.
//
// Значение читается один раз при старте, а не на каждый запрос: лимит должен
// стоить ноль запросов, а менять его можно перезапуском — тем более что сам
// интерфейс админки (S-76) ещё не построен.

import pg from 'pg';

/** Пока ключа нет в настройках (H-24), а подтверждённое автором число — 30. */
export const DEFAULT_RATE_PER_MINUTE = 30;

/**
 * Лимиты поиска из настроек модуля.
 *
 * @param {pg.Pool} pool
 * @returns {Promise<{ratePerIp: number, windowMs: number}>}
 */
export async function searchSettings(pool) {
  const { rows } = await pool.query(
    "SELECT value FROM e_system_setting WHERE key = 'search.rate_limit'",
  );
  const value = Number(rows[0]?.value);
  return {
    ratePerIp: Number.isInteger(value) && value > 0 ? value : DEFAULT_RATE_PER_MINUTE,
    windowMs: 60_000,
  };
}
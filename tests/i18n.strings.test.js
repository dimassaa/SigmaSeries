// Каталог текста: полнота по языкам и поведение на пропущенном ключе.
//
// Файл появился потому, что проверка была написана, но не подключена:
// `t()` бросает исключение на пропущенном ключе, и это правильно, однако
// `missingKeys()` не вызывал никто. Недостающая английская строка ждала бы
// живого экрана и падала 500-й у человека, а не на прогоне, — при том что
// требование «русский обязателен, английский дополнительно» делает расхождение
// каталогов обычным следствием правки, а не редким случаем.
//
// Спецификация: M1 §0, `DEC-026`; правило — `R-I18N-01`.

import test from 'node:test';
import assert from 'node:assert/strict';
import { t, missingKeys, LOCALES, DEFAULT_LOCALE } from '../src/i18n/strings.js';

test('у каждого ключа есть все языки', () => {
  assert.deepEqual(missingKeys(), [], 'каталог расходится между языками');
});

test('языков два, по умолчанию русский', () => {
  // ADR-003: язык по умолчанию русский независимо от заголовков браузера.
  assert.deepEqual(LOCALES, ['ru', 'en']);
  assert.equal(DEFAULT_LOCALE, 'ru');
});

test('пропущенный ключ падает громко, а не пустым местом', () => {
  // Пустая подпись на экране — это человек, объясняющий себе её сам,
  // и обычно неверно. Отсутствие текста должно быть ошибкой сборки.
  assert.throws(() => t('ru', 'такого.ключа.нет'), /Нет ключа/);
  assert.throws(() => t('en', 'такого.ключа.нет'), /Нет ключа/);
});

test('подстановка подставляет параметр и не трогает неизвестный плейсхолдер', () => {
  // Второе важнее первого: фигурные скобки могут быть частью фразы, и молча
  // стирать их нельзя — подпись изменилась бы без ведома переводчика.
  assert.ok(!/\{seconds\}/.test(t('ru', 'signin.error.tooMany', { seconds: 7 })));
  assert.match(t('ru', 'signin.error.tooMany'), /\{seconds\}/);
});
